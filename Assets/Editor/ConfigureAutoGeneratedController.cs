using System;
using System.Collections.Generic;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;

public static class ConfigureAutoGeneratedController
{
    private const string ControllerPath = "Assets/Auto_Generated_Controller.controller";
    private const string ClipFolder = "Assets/anim(aliese)/";
    private const string OrlovPrefabPath = "Assets/npc/team/Kapitan_Orlov/Entity_Orlov.prefab";

    [MenuItem("Tools/Configure Character Animator")]
    public static void Run()
    {
        Dictionary<string, AnimationClip> clips = LoadRequiredClips();
        AnimatorController controller = AssetDatabase.LoadAssetAtPath<AnimatorController>(ControllerPath);
        if (controller == null)
        {
            controller = AnimatorController.CreateAnimatorControllerAtPath(ControllerPath);
        }

        ConfigureParameters(controller);
        ConfigureLayers(controller);
        AssetDatabase.SaveAssets();
        AssetDatabase.Refresh();
        Debug.Log("Configured Auto_Generated_Controller with locomotion, aim, action, hit, and death states.");
    }

    private static Dictionary<string, AnimationClip> LoadRequiredClips()
    {
        string[] names =
        {
            "idle_anim",
            "idle crouching_anim",
            "rifle aiming idle_anim",
            "idle aiming_anim",
            "idle crouching aiming_anim",
            "walk forward_anim",
            "walk backward_anim",
            "walk left_anim",
            "walk right_anim",
            "walk forward left_anim",
            "walk forward right_anim",
            "walk backward left_anim",
            "walk backward right_anim",
            "run forward_anim",
            "run backward_anim",
            "run left_anim",
            "run right_anim",
            "run forward left_anim",
            "run forward right_anim",
            "run backward left_anim",
            "run backward right_anim",
            "sprint forward_anim",
            "sprint backward_anim",
            "sprint left_anim",
            "sprint right_anim",
            "sprint forward left_anim",
            "sprint forward right_anim",
            "sprint backward left_anim",
            "sprint backward right_anim",
            "walk crouching forward_anim",
            "walk crouching backward_anim",
            "walk crouching left_anim",
            "walk crouching right_anim",
            "walk crouching forward left_anim",
            "walk crouching forward right_anim",
            "walk crouching backward left_anim",
            "walk crouching backward right_anim",
            "firing rifle_anim",
            "reloading_anim",
            "toss grenade_anim",
            "hit reaction_anim",
            "death from front headshot_anim",
            "jump up_anim",
            "jump loop_anim",
            "jump down_anim"
        };

        Dictionary<string, AnimationClip> clips = new Dictionary<string, AnimationClip>();
        foreach (string name in names)
        {
            AnimationClip clip = AssetDatabase.LoadAssetAtPath<AnimationClip>(ClipFolder + name + ".anim");
            if (clip == null)
            {
                throw new InvalidOperationException("Required animation clip was not found: " + ClipFolder + name + ".anim");
            }

            clips.Add(name, clip);
        }

        return clips;
    }

    private static void ConfigureParameters(AnimatorController controller)
    {
        AddParameter(controller, "VelocityX", AnimatorControllerParameterType.Float);
        AddParameter(controller, "VelocityY", AnimatorControllerParameterType.Float);
        AddParameter(controller, "MoveAmount", AnimatorControllerParameterType.Float);
        AddParameter(controller, "IsCrouching", AnimatorControllerParameterType.Bool);
        AddParameter(controller, "IsAiming", AnimatorControllerParameterType.Bool);
        AddParameter(controller, "IsGrounded", AnimatorControllerParameterType.Bool);
        AddParameter(controller, "VerticalSpeed", AnimatorControllerParameterType.Float);
        AddParameter(controller, "Fire", AnimatorControllerParameterType.Trigger);
        AddParameter(controller, "Reload", AnimatorControllerParameterType.Trigger);
        AddParameter(controller, "ThrowGrenade", AnimatorControllerParameterType.Trigger);
        AddParameter(controller, "Hit", AnimatorControllerParameterType.Trigger);
        AddParameter(controller, "Die", AnimatorControllerParameterType.Trigger);
    }

    private static void AddParameter(AnimatorController controller, string name, AnimatorControllerParameterType type)
    {
        AnimatorControllerParameter[] parameters = controller.parameters;
        for (int i = 0; i < parameters.Length; i++)
        {
            AnimatorControllerParameter parameter = parameters[i];
            if (parameter.name == name)
            {
                if (parameter.type != type)
                {
                    controller.RemoveParameter(i);
                    break;
                }

                return;
            }
        }

        controller.AddParameter(name, type);
    }

    private static void ConfigureLayers(AnimatorController controller)
    {
        for (int i = controller.layers.Length - 1; i > 0; i--)
        {
            controller.RemoveLayer(i);
        }

        AnimatorControllerLayer[] layers = controller.layers;
        AnimatorStateMachine baseMachine = layers[0].stateMachine;
        foreach (ChildAnimatorState childState in baseMachine.states)
        {
            baseMachine.RemoveState(childState.state);
        }

        UnityEngine.Object[] oldSubAssets = AssetDatabase.LoadAllAssetsAtPath(ControllerPath);
        foreach (UnityEngine.Object subAsset in oldSubAssets)
        {
            if (subAsset != controller && subAsset.name.StartsWith("AGC_", StringComparison.Ordinal))
            {
                UnityEngine.Object.DestroyImmediate(subAsset, true);
            }
        }

        baseMachine.name = "Base Layer";
        ConfigureBaseLayer(controller, baseMachine);

        AvatarMask upperBodyMask = CreateUpperBodyMask(controller);
        ConfigureUpperBodyLayer(controller, "Upper Body Aim", upperBodyMask, "AGC_Aim");
        ConfigureUpperBodyLayer(controller, "Upper Body Actions", upperBodyMask, "AGC_Action");
    }

    private static void ConfigureBaseLayer(AnimatorController controller, AnimatorStateMachine machine)
    {
        Dictionary<string, AnimationClip> clips = LoadRequiredClips();
        BlendTree walk = CreateDirectionalTree(controller, clips, "AGC_Walk", "walk", false);
        BlendTree run = CreateDirectionalTree(controller, clips, "AGC_Run", "run", false);
        BlendTree sprint = CreateDirectionalTree(controller, clips, "AGC_Sprint", "sprint", false);
        BlendTree crouch = CreateDirectionalTree(controller, clips, "AGC_Crouch", "walk crouching", true);
        BlendTree locomotion = CreateSpeedTree(controller, clips, "AGC_Locomotion", walk, run, sprint);

        AnimatorState moveState = machine.AddState("Locomotion", new Vector3(280f, 80f, 0f));
        moveState.motion = locomotion;
        AnimatorState crouchState = machine.AddState("Crouched Locomotion", new Vector3(520f, 80f, 0f));
        crouchState.motion = crouch;
        machine.defaultState = moveState;

        AnimatorStateTransition toCrouch = moveState.AddTransition(crouchState);
        ConfigureTransition(toCrouch, 0.12f);
        toCrouch.AddCondition(AnimatorConditionMode.If, 0f, "IsCrouching");
        AnimatorStateTransition fromCrouch = crouchState.AddTransition(moveState);
        ConfigureTransition(fromCrouch, 0.12f);
        fromCrouch.AddCondition(AnimatorConditionMode.IfNot, 0f, "IsCrouching");

        AnimatorState jumpUp = machine.AddState("Jump Up", new Vector3(280f, 250f, 0f));
        jumpUp.motion = clips["jump up_anim"];
        AnimatorState jumpLoop = machine.AddState("Jump Loop", new Vector3(520f, 250f, 0f));
        jumpLoop.motion = clips["jump loop_anim"];
        AnimatorState jumpDown = machine.AddState("Jump Down", new Vector3(760f, 250f, 0f));
        jumpDown.motion = clips["jump down_anim"];
        AnimatorStateTransition toJump = moveState.AddTransition(jumpUp);
        ConfigureTransition(toJump, 0.08f);
        toJump.AddCondition(AnimatorConditionMode.IfNot, 0f, "IsGrounded");
        toJump.AddCondition(AnimatorConditionMode.Greater, 0f, "VerticalSpeed");
        AnimatorStateTransition crouchToJump = crouchState.AddTransition(jumpUp);
        ConfigureTransition(crouchToJump, 0.08f);
        crouchToJump.AddCondition(AnimatorConditionMode.IfNot, 0f, "IsGrounded");
        crouchToJump.AddCondition(AnimatorConditionMode.Greater, 0f, "VerticalSpeed");
        AnimatorStateTransition jumpToLoop = jumpUp.AddTransition(jumpLoop);
        ConfigureTransition(jumpToLoop, 0.08f);
        jumpToLoop.hasExitTime = true;
        jumpToLoop.exitTime = 0.85f;
        AnimatorStateTransition loopToDown = jumpLoop.AddTransition(jumpDown);
        ConfigureTransition(loopToDown, 0.08f);
        loopToDown.AddCondition(AnimatorConditionMode.If, 0f, "IsGrounded");
        AnimatorStateTransition downToMove = jumpDown.AddTransition(moveState);
        ConfigureTransition(downToMove, 0.12f);
        downToMove.hasExitTime = true;
        downToMove.exitTime = 0.85f;

        AnimatorState hit = machine.AddState("Hit Reaction", new Vector3(760f, 80f, 0f));
        hit.motion = clips["hit reaction_anim"];
        AnimatorStateTransition hitTransition = machine.AddAnyStateTransition(hit);
        ConfigureTransition(hitTransition, 0.05f);
        hitTransition.AddCondition(AnimatorConditionMode.If, 0f, "Hit");
        AnimatorStateTransition recover = hit.AddTransition(moveState);
        ConfigureTransition(recover, 0.1f);
        recover.hasExitTime = true;
        recover.exitTime = 0.9f;

        AnimatorState death = machine.AddState("Death", new Vector3(1000f, 80f, 0f));
        death.motion = clips["death from front headshot_anim"];
        AnimatorStateTransition deathTransition = machine.AddAnyStateTransition(death);
        ConfigureTransition(deathTransition, 0.05f);
        deathTransition.AddCondition(AnimatorConditionMode.If, 0f, "Die");
    }

    private static BlendTree CreateSpeedTree(
        AnimatorController controller,
        Dictionary<string, AnimationClip> clips,
        string name,
        BlendTree walk,
        BlendTree run,
        BlendTree sprint)
    {
        BlendTree tree = new BlendTree
        {
            name = name,
            blendType = BlendTreeType.Simple1D,
            blendParameter = "MoveAmount",
            useAutomaticThresholds = false
        };
        tree.AddChild(clips["idle_anim"], 0f);
        tree.AddChild(walk, 0.45f);
        tree.AddChild(run, 1f);
        tree.AddChild(sprint, 1.7f);
        AddSubAsset(controller, tree);
        return tree;
    }

    private static BlendTree CreateDirectionalTree(
        AnimatorController controller,
        Dictionary<string, AnimationClip> clips,
        string name,
        string prefix,
        bool crouched)
    {
        prefix += " ";
        BlendTree tree = new BlendTree
        {
            name = name,
            blendType = BlendTreeType.FreeformDirectional2D,
            blendParameter = "VelocityX",
            blendParameterY = "VelocityY",
            useAutomaticThresholds = false
        };

        if (crouched)
        {
            tree.AddChild(clips["idle crouching_anim"], Vector2.zero);
        }

        AddDirectionalClip(tree, clips, prefix + "forward_anim", new Vector2(0f, 1f));
        AddDirectionalClip(tree, clips, prefix + "backward_anim", new Vector2(0f, -1f));
        AddDirectionalClip(tree, clips, prefix + "left_anim", new Vector2(-1f, 0f));
        AddDirectionalClip(tree, clips, prefix + "right_anim", new Vector2(1f, 0f));
        AddDirectionalClip(tree, clips, prefix + "forward left_anim", new Vector2(-0.7f, 0.7f));
        AddDirectionalClip(tree, clips, prefix + "forward right_anim", new Vector2(0.7f, 0.7f));
        AddDirectionalClip(tree, clips, prefix + "backward left_anim", new Vector2(-0.7f, -0.7f));
        AddDirectionalClip(tree, clips, prefix + "backward right_anim", new Vector2(0.7f, -0.7f));
        AddSubAsset(controller, tree);
        return tree;
    }

    private static void AddDirectionalClip(
        BlendTree tree,
        Dictionary<string, AnimationClip> clips,
        string name,
        Vector2 position)
    {
        AnimationClip clip;
        if (clips.TryGetValue(name, out clip))
        {
            tree.AddChild(clip, position);
        }
        else
        {
            throw new InvalidOperationException("Directional animation clip was not found: " + name);
        }
    }

    private static AvatarMask CreateUpperBodyMask(AnimatorController controller)
    {
        AvatarMask mask = new AvatarMask();
        mask.name = "AGC_UpperBodyMask";

        GameObject prefab = PrefabUtility.LoadPrefabContents(OrlovPrefabPath);
        try
        {
            Animator[] animators = prefab.GetComponentsInChildren<Animator>(true);
            Animator sourceAnimator = null;
            foreach (Animator animator in animators)
            {
                if (animator.avatar != null)
                {
                    sourceAnimator = animator;
                    break;
                }
            }

            if (sourceAnimator == null)
            {
                throw new InvalidOperationException("Orlov prefab has no Animator Avatar to build the upper-body mask.");
            }

            mask.AddTransformPath(sourceAnimator.transform, true);
            int activePaths = 0;
            for (int i = 0; i < mask.transformCount; i++)
            {
                string path = mask.GetTransformPath(i);
                string boneName = path.Substring(path.LastIndexOf('/') + 1);
                bool active = IsUpperBodyBone(boneName);
                mask.SetTransformActive(i, active);
                if (active)
                {
                    activePaths++;
                }
            }

            if (activePaths == 0)
            {
                throw new InvalidOperationException("No Mixamo spine or arm bones were found for the upper-body mask.");
            }
        }
        finally
        {
            PrefabUtility.UnloadPrefabContents(prefab);
        }

        AddSubAsset(controller, mask);
        return mask;
    }

    private static bool IsUpperBodyBone(string boneName)
    {
        return boneName.Contains("mixamorig:Spine") ||
               boneName.Contains("mixamorig:LeftShoulder") ||
               boneName.Contains("mixamorig:LeftArm") ||
               boneName.Contains("mixamorig:LeftForeArm") ||
               boneName.Contains("mixamorig:LeftHand") ||
               boneName.Contains("mixamorig:RightShoulder") ||
               boneName.Contains("mixamorig:RightArm") ||
               boneName.Contains("mixamorig:RightForeArm") ||
               boneName.Contains("mixamorig:RightHand");
    }

    private static void ConfigureUpperBodyLayer(
        AnimatorController controller,
        string layerName,
        AvatarMask mask,
        string prefix)
    {
        controller.AddLayer(layerName);
        AnimatorControllerLayer[] layers = controller.layers;
        int layerIndex = layers.Length - 1;
        layers[layerIndex].avatarMask = mask;
        layers[layerIndex].blendingMode = AnimatorLayerBlendingMode.Override;
        layers[layerIndex].defaultWeight = 0f;
        layers[layerIndex].iKPass = false;
        AnimatorStateMachine machine = layers[layerIndex].stateMachine;
        machine.name = layerName;

        AnimatorState empty = machine.AddState(prefix + "_Empty", new Vector3(100f, 80f, 0f));
        machine.defaultState = empty;

        if (layerName == "Upper Body Aim")
        {
            AnimatorState aimStanding = machine.AddState(prefix + "_AimStanding", new Vector3(340f, 20f, 0f));
            aimStanding.motion = AssetDatabase.LoadAssetAtPath<AnimationClip>(ClipFolder + "rifle aiming idle_anim.anim");
            AnimatorState aimCrouched = machine.AddState(prefix + "_AimCrouched", new Vector3(340f, 140f, 0f));
            aimCrouched.motion = AssetDatabase.LoadAssetAtPath<AnimationClip>(ClipFolder + "idle crouching aiming_anim.anim");

            AnimatorStateTransition toStandingAim = empty.AddTransition(aimStanding);
            ConfigureTransition(toStandingAim, 0.15f);
            toStandingAim.AddCondition(AnimatorConditionMode.If, 0f, "IsAiming");
            toStandingAim.AddCondition(AnimatorConditionMode.IfNot, 0f, "IsCrouching");
            AnimatorStateTransition toCrouchedAim = empty.AddTransition(aimCrouched);
            ConfigureTransition(toCrouchedAim, 0.15f);
            toCrouchedAim.AddCondition(AnimatorConditionMode.If, 0f, "IsAiming");
            toCrouchedAim.AddCondition(AnimatorConditionMode.If, 0f, "IsCrouching");
            AddAimExit(aimStanding, empty, "IsAiming");
            AddAimExit(aimCrouched, empty, "IsAiming");
            return;
        }

        AddActionState(machine, empty, prefix + "_Fire", "firing rifle_anim", "Fire", false);
        AddActionState(machine, empty, prefix + "_Reload", "reloading_anim", "Reload", true);
        AddActionState(machine, empty, prefix + "_ThrowGrenade", "toss grenade_anim", "ThrowGrenade", true);
    }

    private static void AddActionState(
        AnimatorStateMachine machine,
        AnimatorState empty,
        string stateName,
        string clipName,
        string trigger,
        bool useExitTime)
    {
        AnimationClip clip = AssetDatabase.LoadAssetAtPath<AnimationClip>(ClipFolder + clipName + ".anim");
        if (clip == null)
        {
            throw new InvalidOperationException("Required action clip was not found: " + clipName);
        }

        AnimatorState state = machine.AddState(stateName, new Vector3(340f, machine.states.Length * 80f, 0f));
        state.motion = clip;
        AnimatorStateTransition start = empty.AddTransition(state);
        ConfigureTransition(start, 0.05f);
        start.AddCondition(AnimatorConditionMode.If, 0f, trigger);
        AnimatorStateTransition end = state.AddTransition(empty);
        ConfigureTransition(end, 0.08f);
        end.hasExitTime = true;
        end.exitTime = useExitTime ? 0.9f : 0.95f;
    }

    private static void AddAimExit(AnimatorState aim, AnimatorState empty, string parameter)
    {
        AnimatorStateTransition transition = aim.AddTransition(empty);
        ConfigureTransition(transition, 0.15f);
        transition.AddCondition(AnimatorConditionMode.IfNot, 0f, parameter);
    }

    private static void ConfigureTransition(AnimatorStateTransition transition, float duration)
    {
        transition.hasExitTime = false;
        transition.hasFixedDuration = true;
        transition.duration = duration;
        transition.offset = 0f;
        transition.canTransitionToSelf = false;
    }

    private static void AddSubAsset(AnimatorController controller, UnityEngine.Object subAsset)
    {
        subAsset.hideFlags = HideFlags.HideInHierarchy;
        AssetDatabase.AddObjectToAsset(subAsset, controller);
    }
}
